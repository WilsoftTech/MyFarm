import { z } from "zod";
import { idSchema } from "@/modules/engineering-foundation/contracts/identity";
import type { ProductionWriteScope } from "@/modules/enterprises-seasons/contracts/production";
import { isCalendarDate } from "@/modules/enterprises-seasons/domain/production";
import { MISSING_REASONS, type BatchTrendEvaluation, type InsightCandidate, type MissingReason, type TrendFigureRule } from "../domain/batch-trends";
import { INSIGHT_STATUSES, type InsightStatus } from "../domain/insight-state";
import { RULE_KEYS, SEVERITIES, type RuleKey, type Severity } from "../domain/rules";

/**
 * Farm intelligence contracts (MYF-P10-R001). Insights are generated by the server from the farm's own records;
 * a client can only acknowledge one it was shown. The stored evidence is versioned JSON, validated when read back,
 * so an insight always shows the values, windows, rule version and coverage it was raised on (MYF-P10-AC001).
 */
const calendarDay = z.string().refine(isCalendarDate);
const decimal = z.string().regex(/^-?\d{1,40}(?:\.\d{1,6})?$/);
const integer = z.string().regex(/^-?\d{1,80}$/);
const window = z.object({ from: calendarDay, to: calendarDay }).strict();
const windowCoverage = z.object({ birdsAtStart: integer, recordedDays: z.array(z.number().int().min(0).max(7)).length(4), eggDays: z.array(z.number().int().min(0).max(7)).length(4) }).strict();
const figure = z.object({
  rule: z.enum(["FEED_COST_RISING", "EGGS_FALLING", "MORTALITY_RISING"]),
  currency: z.string().regex(/^[A-Z]{3}$/).nullable(),
  outcome: z.enum(["RAISED", "NOT_RAISED", "NOT_ENOUGH_RECORDS"]),
  missing: z.array(z.enum(MISSING_REASONS)),
  earlier: decimal.nullable(), current: decimal.nullable(), change: decimal.nullable(),
  exactChange: z.object({ numerator: integer, denominator: integer.refine(value => BigInt(value) > 0n) }).strict().nullable(),
}).strict();
export const EVIDENCE_VERSION = 1;
export const insightEvidenceSchema = z.object({
  evidenceVersion: z.literal(EVIDENCE_VERSION),
  batchLabel: z.string().min(1).max(120),
  windows: z.object({ earlier: window, current: window }).strict(),
  coverage: z.object({ earlier: windowCoverage, current: windowCoverage }).strict(),
  figures: z.array(figure).min(1).max(2),
}).strict();
export type InsightEvidence = z.output<typeof insightEvidenceSchema>;

export function evidenceOf(evaluation: BatchTrendEvaluation, candidate: InsightCandidate): InsightEvidence {
  return insightEvidenceSchema.parse({ evidenceVersion: EVIDENCE_VERSION, batchLabel: evaluation.label, windows: evaluation.windows, coverage: evaluation.coverage, figures: candidate.figures });
}

/** The insight is named by the route; the body carries only the retry key and the version the farmer saw. */
export const acknowledgeInsightSchema = z.object({ requestId: idSchema, expectedVersion: z.number().int().positive().max(2147483646) }).strict();
export type AcknowledgeInsight = z.output<typeof acknowledgeInsightSchema>;

export interface InsightView {
  insightId: string;
  batchId: string;
  ruleKey: RuleKey;
  ruleVersion: number;
  severity: Severity;
  status: InsightStatus;
  currency: string | null;
  evaluatedOn: string;
  evidence: InsightEvidence;
  acknowledgedAt: string | null;
  version: number;
}
/** The feed: live insights, most serious first, and for each active batch the figures that could not be judged and why. */
export interface InsightFeed { evaluatedOn: string; insights: InsightView[]; notJudged: { batchId: string; batchLabel: string; rule: TrendFigureRule; currency: string | null; missing: MissingReason[] }[]; batchesChecked: number; batchesTruncated: boolean }
/** Farms in the launch market keep few batches at a time; the feed reads at most this many active ones, newest first. */
export const MAX_INSIGHT_BATCHES = 50;

export interface InsightRepository {
  /** Evaluates the farm's active batches on the farm date and applies the repeat rule in one transaction. */
  generate(scope: ProductionWriteScope, today: string): Promise<InsightFeed>;
  acknowledge(scope: ProductionWriteScope, insightId: string, command: AcknowledgeInsight): Promise<InsightView>;
}

export const ruleKeySchema = z.enum(RULE_KEYS);
export const severitySchema = z.enum(SEVERITIES);
export const insightStatusSchema = z.enum(INSIGHT_STATUSES);
