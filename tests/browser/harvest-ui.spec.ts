import { test, expect } from "@playwright/test";
import { z } from "zod";
import { Client } from "pg";
import {mkdirSync} from "node:fs";
import {prepareInventoryBrowser,clearInventoryBrowser} from "../support/inventory-browser";

test("harvest entry preserves offline input, posts once and denies foreign farm access", async ({ page, context }, info) => {
  const f = await prepareInventoryBrowser(), farm = f.farms.a;
  await context.addCookies([{ name: "sb-127-auth-token", value: f.accounts.a.cookie, url: "http://127.0.0.1:3102", httpOnly: true, sameSite: "Lax" }]);
  const headers = { origin: "http://127.0.0.1:3102" }, id = () => crypto.randomUUID();
  const post = async (path: string, data: object) => { const r = await context.request.post(`/api/v1/farms/${farm}/${path}`, { headers, data }); expect(r.status()).toBe(201); return r.json(); };
  try {
    const e = z.object({ enterprise: z.object({ enterpriseId: z.uuid() }) }).parse(await post("enterprises", { requestId: id(), name: "Harvest crop " + id(), type: "CROP" })).enterprise;
    const s = z.object({ season: z.object({ seasonId: z.uuid() }) }).parse(await post("seasons", { requestId: id(), label: "Harvest season " + id(), startDate: "2026-03-01" })).season;
    const p = z.object({ plotId: z.uuid() }).parse(await post("plots", { requestId: id(), name: "Harvest plot " + id(), area: "1", areaUnit: "ACRE" }));
    const c = z.object({ cycle: z.object({ cycleId: z.uuid() }) }).parse(await post("crop-cycles", { requestId: id(), enterpriseId: e.enterpriseId, seasonId: s.seasonId, plotId: p.plotId, cropId: "f4030005-0000-4000-8000-000000000001", plantingDate: "2026-03-01", areaPlanted: "1", areaUnit: "ACRE" })).cycle;
    const store = z.object({ location: z.object({ storageLocationId: z.uuid() }) }).parse(await post("storage-locations", { requestId: id(), name: "Harvest store " + id() })).location;
    await page.goto(`/farms/${farm}/harvests/new`);
    await page.getByLabel("Crop cycle", { exact: true }).selectOption(c.cycleId);
    await page.getByLabel("Store", { exact: true }).selectOption(store.storageLocationId);
    await page.getByLabel("Harvest date", { exact: true }).fill("2026-10-01");
    await page.getByLabel("Harvested kilograms", { exact: true }).fill("2400");
    await page.getByLabel("Initial loss in kilograms", { exact: true }).fill("150");
    await context.setOffline(true);
    await expect(page.getByRole("button", { name: "Save harvest" })).toBeDisabled();
    await expect(page.getByLabel("Harvested kilograms", { exact: true })).toHaveValue("2400");
    await context.setOffline(false);
    await page.getByRole("button", { name: "Save harvest" }).click();
    await expect(page.getByRole("heading", { name: "Maize harvest" })).toBeVisible();
    await expect(page.getByText("2250 kg", { exact: true })).toBeVisible();
    const harvestId = page.url().split("/").pop();
    expect((await context.request.get(`/api/v1/farms/${f.farms.a2}/harvests/${harvestId}`)).status()).toBe(403);
    expect((await context.request.post(`/api/v1/farms/${farm}/harvests`, { headers, data: { requestId: id(), cropCycleId: c.cycleId, cropId: "f4030005-0000-4000-8000-000000000001", plotId: id(), storageLocationId: store.storageLocationId, harvestDate: "2026-10-01", quantity: "1", unit: "BAG" } })).status()).toBe(400);
    const detail = await context.request.get(`/api/v1/farms/${farm}/harvests/${harvestId}`);
    const itemId = z.object({harvest:z.object({itemId:z.uuid()})}).parse(await detail.json()).harvest.itemId;
    const categories = z.object({items:z.array(z.object({categoryId:z.uuid()}))}).parse(await (await context.request.get(`/api/v1/farms/${farm}/accounting/categories?kind=REVENUE`)).json());
    await page.goto(`/farms/${farm}/inventory/new`);
    await page.getByLabel("Inventory item",{exact:true}).selectOption(itemId);
    await expect(page.getByLabel("Unit",{exact:true})).toHaveValue("KG");
    await page.getByLabel("From store",{exact:true}).selectOption(store.storageLocationId);
    await page.getByLabel("Operation",{exact:true}).selectOption("SALE");
    await page.getByLabel("Quantity",{exact:true}).fill("1600");
    await page.getByLabel("Movement date",{exact:true}).fill("2026-10-01");
    await page.getByLabel("Reason",{exact:true}).fill("Harvest sold");
    await page.getByLabel("Sale category (optional)",{exact:true}).selectOption(categories.items[0].categoryId);
    await page.getByLabel("Sale amount (optional)",{exact:true}).fill("200000");
    await page.getByLabel("Sale currency (optional)",{exact:true}).fill("UGX");
    await page.getByRole("button",{name:"Save stock movement"}).click();
    await expect(page.getByRole("heading",{name:"Inventory",exact:true})).toBeVisible();
    await expect(page.getByText(/: 650 KG$/)).toBeVisible();
    const dest = z.object({location:z.object({storageLocationId:z.uuid()})}).parse(await post("storage-locations",{requestId:id(),name:"Destination "+id()})).location;
    await page.goto(`/farms/${farm}/inventory/new`);
    await page.getByLabel("Inventory item",{exact:true}).selectOption(itemId);
    await page.getByLabel("From store",{exact:true}).selectOption(store.storageLocationId);
    await page.getByLabel("Operation",{exact:true}).selectOption("TRANSFER");
    await page.getByLabel("Quantity",{exact:true}).fill("150");
    await page.getByLabel("Movement date",{exact:true}).fill("2026-10-01");
    await page.getByLabel("Reason",{exact:true}).fill("Move to dry store");
    await page.getByLabel("Destination store (optional)",{exact:true}).selectOption(dest.storageLocationId);
    await page.getByRole("button",{name:"Save stock movement"}).click();
    await expect(page.getByText(/: 500 KG$/)).toBeVisible();await expect(page.getByText(/: 150 KG$/)).toBeVisible();
    await page.getByRole("link",{name:"Stock operations",exact:true}).click();
    await page.getByRole("link",{name:"Review reversal",exact:true}).first().click();
    await page.getByLabel("Reversal date",{exact:true}).fill("2026-10-01");
    await page.getByLabel("Reason for reversal",{exact:true}).fill("Wrong destination");
    await page.getByLabel("I have reviewed this correction",{exact:true}).check();
    await page.getByRole("button",{name:"Confirm reversal"}).click();
    await expect(page.getByText(/: 650 KG$/)).toBeVisible();
    await page.getByRole("link",{name:"Maize",exact:true}).click();
    await expect(page.getByRole("status")).toHaveText("Display matches movement history.");
    await expect(page.getByText("650 KG",{exact:true})).toBeVisible();
    await page.getByRole("button",{name:"Recalculate stock"}).click();
    await expect(page.getByRole("button",{name:"Recalculate stock"})).toBeEnabled();
    await expect(page.getByRole("status")).toHaveText("Display matches movement history.");
    await page.getByRole("link",{name:"View movement history"}).click();
    await expect(page.getByRole("heading",{name:"Stock movement history"})).toBeVisible();
    await expect(page.getByText("sale: -1600 KG",{exact:true})).toBeVisible();
    expect((await context.request.get(`/api/v1/farms/${f.farms.a2}/inventory-items/${itemId}/history`)).status()).toBe(403);
    mkdirSync(".cache/p05-visual",{recursive:true});await page.screenshot({path:`.cache/p05-visual/history-${info.project.name}.png`,fullPage:true});
    const db = new Client({ connectionString: process.env.TEST_DATABASE_URL }); await db.connect();
    try { expect((await db.query('SELECT count(*)::int AS n FROM "StockMovement" WHERE "harvestId"=$1', [harvestId])).rows[0].n).toBe(2); }
    finally { await db.end(); }
  } finally {
    await context.setOffline(false);
    await clearInventoryBrowser(f);
  }
});
